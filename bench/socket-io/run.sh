#!/usr/bin/env bash
# Socket.IO benchmark of Corvis: emit, server-emit and broadcast over WebSocket and long-polling.
#
# Usage (Git Bash on Windows, or any POSIX shell; from any directory):
#   bash bench/socket-io/run.sh
#
# The variables, the prerequisites and where the binary is built are described in bench/socket-io/README.md.
# The server listens on 127.0.0.1 only; one server process runs at a time.

set -euo pipefail

BENCH_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$BENCH_DIR/../.." && pwd)"
RAW_DIR="$BENCH_DIR/raw"
RESULTS="$BENCH_DIR/results.md"

WS_CONNECTIONS="${WS_CONNECTIONS:-1000}"
POLLING_CONNECTIONS="${POLLING_CONNECTIONS:-200}"
MESSAGES="${MESSAGES:-100}"
SIZE="${SIZE:-64}"
LARGE_SIZE="${LARGE_SIZE:-}"
RUNS="${RUNS:-3}"
SCENARIOS="${SCENARIOS:-emit server-emit broadcast}"
TRANSPORTS="${TRANSPORTS:-websocket polling}"
PORT="${PORT:-3300}"
BUILD_CMD="cargo build --release -p corvis-sio-bench"

log() { printf '\033[36m[sio-bench]\033[0m %s\n' "$*"; }
die() { printf '\033[31m[sio-bench] ERROR:\033[0m %s\n' "$*" >&2; exit 1; }

# The target directory Cargo uses for the workspace (CARGO_TARGET_DIR, a Cargo config, or <repo>/target), with forward
# slashes.
target_dir() {
  (cd "$ROOT_DIR" && cargo metadata --no-deps --format-version 1) |
    sed -E 's/.*"target_directory":"([^"]*)".*/\1/' | sed -E 's#\\\\#/#g'
}

SERVER_PID=""
stop_server() {
  [ -n "$SERVER_PID" ] || return 0
  local winpid
  winpid="$(cat "/proc/$SERVER_PID/winpid" 2> /dev/null || true)"
  if [ -n "$winpid" ] && command -v taskkill > /dev/null 2>&1; then
    taskkill //F //T //PID "$winpid" > /dev/null 2>&1 || true
  else
    kill "$SERVER_PID" 2> /dev/null || true
  fi
  wait "$SERVER_PID" 2> /dev/null || true
  SERVER_PID=""
}
trap stop_server EXIT INT TERM

TARGET_DIR="$(target_dir)" || die "Could not resolve the Cargo target directory (cargo metadata failed)."
[ -n "$TARGET_DIR" ] || die "Could not resolve the Cargo target directory."
EXE="$TARGET_DIR/release/corvis-sio-bench"
[ -f "$EXE.exe" ] && EXE="$EXE.exe"

if [ "${SKIP_BUILD:-0}" != "1" ]; then
  log "Building corvis-sio-bench (--release) in $TARGET_DIR/release..."
  (cd "$ROOT_DIR" && $BUILD_CMD) || die "The build failed."
  [ -f "$EXE.exe" ] && EXE="$EXE.exe"
fi
[ -f "$EXE" ] || die "$EXE does not exist. Build it with: $BUILD_CMD"

command -v curl > /dev/null 2>&1 || die "'curl' not found."

rm -rf "$RAW_DIR"
mkdir -p "$RAW_DIR"

start_server() {
  "$EXE" server --port "$PORT" > "$RAW_DIR/server-$1.log" 2>&1 &
  SERVER_PID=$!
  local i
  for i in $(seq 1 100); do
    if curl -s -m 1 -o /dev/null "http://127.0.0.1:$PORT/stats"; then return 0; fi
    sleep 0.2
  done
  die "The server did not answer on 127.0.0.1:$PORT (see $RAW_DIR/server-$1.log)."
}

# measure <scenario> <transport> <size>: one server, RUNS runs of the load generator.
measure() {
  local scenario="$1" transport="$2" size="$3" connections run
  connections="$WS_CONNECTIONS"
  [ "$transport" = "polling" ] && connections="$POLLING_CONNECTIONS"
  local name="$scenario-$transport-$size"
  log "$scenario over $transport: $connections connections x $MESSAGES messages of $size bytes, $RUNS runs"
  start_server "$name"
  for run in $(seq 1 "$RUNS"); do
    "$EXE" load --port "$PORT" --scenario "$scenario" --transport "$transport" \
      --connections "$connections" --messages "$MESSAGES" --size "$size" >> "$RAW_DIR/$name.json" ||
      die "The load generator failed ($name, run $run)."
  done
  stop_server
}

for transport in $TRANSPORTS; do
  for scenario in $SCENARIOS; do
    measure "$scenario" "$transport" "$SIZE"
  done
done
if [ -n "$LARGE_SIZE" ]; then
  for transport in $TRANSPORTS; do
    for scenario in server-emit broadcast; do
      measure "$scenario" "$transport" "$LARGE_SIZE"
    done
  done
fi

{
  echo "# Socket.IO benchmark results"
  echo
  echo "Generated by \`bench/socket-io/run.sh\` on $(date '+%Y-%m-%d %H:%M') ($(uname -s), $(git -C "$ROOT_DIR" rev-parse --short HEAD 2> /dev/null || echo unknown))."
  echo "Each figure is the median of $RUNS runs, with the minimum and maximum in parentheses. Allocations and bytes are"
  echo "the server's, counted over the measured window and divided by the messages delivered."
  echo
  "$EXE" report "$RAW_DIR"
} > "$RESULTS"
log "Results written to $RESULTS"
