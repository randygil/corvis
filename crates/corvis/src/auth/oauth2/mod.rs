//! OAuth2 login: the authorization code flow of `passport-oauth2`, with the Google and GitHub profiles of
//! `passport-google-oauth20` and `passport-github2` and the refresh request of `passport-oauth2-refresh`. Needs the
//! `auth-oauth2` cargo feature.
//!
//! An application implements [`OAuth2Validator`] (the options and `validate`), registers
//! `Provider::strategy::<OAuth2Strategy<V>>()` and puts `AuthGuard::new("google")` on two routes: the login route, which
//! redirects to the provider, and the callback route, whose handler runs with the user `validate` returned.
//!
//! What is stricter than the original, on purpose (the docs list each one):
//!
//! - `state` and PKCE `S256` are always on, generated by the operating system's generator, bound to the browser (a
//!   signed `__Host-` cookie or the session), checked in constant time before any request to the provider, and used
//!   once;
//! - the redirect URI is an absolute URL from the configuration, never built from the request;
//! - the client that talks to the provider verifies TLS, follows no redirect, ignores proxy variables, has deadlines
//!   and size limits, and never puts provider text in an error, a log line or a response;
//! - a callback that fails because of the request (a forged state, a provider `error`, a rejected code) answers 401, or
//!   redirects to a configured failure page, never a 500;
//! - nothing that holds a token, a secret, a code or personal data prints it with `Debug`.

