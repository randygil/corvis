//! `schema.prisma` → Rust code generator (`corvis-orm generate`).
//!
//! Every `model`/`view` becomes a `#[derive(Model)]` struct and every `enum` a
//! `#[derive(OrmEnum)]` enum. Conventions:
//!
//! - Rust fields are `snake_case`; `#[serde(rename = "...")]` keeps the schema name in
//!   JSON and in query arguments, `#[map("...")]` keeps the column (`@map` or the schema
//!   name).
//! - Scalars come first in schema order, then relations in schema order, then `_count`
//!   (that is the key order of the results with `include`).
//! - Types: `String`, `i32` (Int), `i64` (BigInt), `f64` (Float), `corvis_orm::Decimal`,
//!   `bool`, `corvis_orm::DateTime`, `serde_json::Value` (Json), `Vec<u8>` (Bytes),
//!   `Option<T>` for `?`, `Vec<T>` for lists.
//! - Relations: to-many `Option<Vec<T>>`, required to-one `Option<Box<T>>`, nullable
//!   to-one `Option<Option<Box<T>>>` (absent = not included, `Some(None)` = `null`).
//! - `Unsupported("...")` fields, `@ignore` fields and `@@ignore` models are left out of
//!   the client (unsupported columns are recorded for `db push`).

use crate::psl::{Arity, Attribute, Expr, Field, Model, Schema};
use std::fmt::Write;

/// Generator options.
#[derive(Debug, Clone)]
pub struct Options {
    /// Extra derives for models and enums (for example `"Default"` is not valid for
    /// every model, but `"schemars::JsonSchema"` may be).
    pub extra_derives: Vec<String>,
    /// Emit `///` doc comments from the schema.
    pub docs: bool,
    /// Header comment (source path).
    pub source: Option<String>,
}

impl Default for Options {
    fn default() -> Self {
        Options { extra_derives: vec![], docs: true, source: None }
    }
}

const SCALARS: &[&str] = &["String", "Int", "BigInt", "Float", "Decimal", "Boolean", "DateTime", "Json", "Bytes"];

/// Rust strict and reserved keywords.
const KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod",
    "move", "mut", "pub", "ref", "return", "static", "struct", "trait", "true", "type", "unsafe", "use", "where", "while", "async",
    "await", "dyn", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield",
    "try", "gen",
];

/// `camelCase` / `PascalCase` → `snake_case` (acronyms kept together: `bcvRateUSD` → `bcv_rate_usd`).
pub fn snake_case(s: &str) -> String {
    let chars: Vec<char> = s.chars().collect();
    let mut out = String::new();
    for (i, c) in chars.iter().enumerate() {
        if c.is_uppercase() {
            let prev_lower = i > 0 && (chars[i - 1].is_lowercase() || chars[i - 1].is_ascii_digit());
            let next_lower = i + 1 < chars.len() && chars[i + 1].is_lowercase();
            let prev_upper = i > 0 && chars[i - 1].is_uppercase();
            if i > 0 && chars[i - 1] != '_' && (prev_lower || (prev_upper && next_lower)) {
                out.push('_');
            }
            out.extend(c.to_lowercase());
        } else {
            out.push(*c);
        }
    }
    out
}

/// A valid Rust identifier for `name` (`type` → `r#type`, `self` → `self_`).
pub fn rust_ident(name: &str) -> String {
    match name {
        "self" | "Self" | "super" | "crate" | "_" => format!("{name}_"),
        n if KEYWORDS.contains(&n) => format!("r#{n}"),
        n if n.starts_with(|c: char| c.is_ascii_digit()) => format!("_{n}"),
        n => n.to_string(),
    }
}

fn rust_str(s: &str) -> String {
    format!("{s:?}")
}

fn doc_lines(out: &mut String, doc: &Option<String>, indent: &str, enabled: bool) {
    if !enabled {
        return;
    }
    if let Some(d) = doc {
        for line in d.lines() {
            let line = line.trim_end();
            if line.is_empty() {
                let _ = writeln!(out, "{indent}///");
            } else {
                let _ = writeln!(out, "{indent}/// {line}");
            }
        }
    }
}

/// Error returned for schemas the generator cannot represent.
#[derive(Debug, Clone)]
pub struct CodegenError(pub String);

impl std::fmt::Display for CodegenError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for CodegenError {}

fn ignored_model(m: &Model) -> bool {
    m.attribute("ignore").is_some()
}

/// Generates the Rust module for `schema`.
pub fn generate(schema: &Schema, opts: &Options) -> Result<String, CodegenError> {
    let mut out = String::new();
    let _ = writeln!(out, "// Generated by corvis-orm from {}. Do not edit by hand.", opts.source.as_deref().unwrap_or("schema.prisma"));
    let _ = writeln!(out, "// Regenerate with: corvis-orm generate");
    let _ = writeln!(out);
    let extra: String = opts.extra_derives.iter().map(|d| format!(", {d}")).collect();

    // ----- enums -----
    for e in &schema.enums {
        doc_lines(&mut out, &e.documentation, "", opts.docs);
        let _ = writeln!(
            out,
            "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, ::corvis_orm::serde::Serialize, ::corvis_orm::serde::Deserialize, ::corvis_orm::OrmEnum{extra})]"
        );
        let _ = writeln!(out, "#[serde(crate = \"::corvis_orm::serde\")]");
        let mut pe = format!("name = {}", rust_str(&e.name));
        if e.db_name() != e.name {
            let _ = write!(pe, ", map = {}", rust_str(&e.db_name()));
        }
        if let Some(s) = e.schema() {
            let _ = write!(pe, ", schema = {}", rust_str(&s));
        }
        let _ = writeln!(out, "#[orm_enum({pe})]");
        let _ = writeln!(out, "#[allow(non_camel_case_types, clippy::upper_case_acronyms)]");
        let _ = writeln!(out, "pub enum {} {{", rust_ident(&e.name));
        for v in &e.values {
            doc_lines(&mut out, &v.documentation, "    ", opts.docs);
            let ident = rust_ident(&v.name);
            if ident.trim_start_matches("r#") != v.name {
                let _ = writeln!(out, "    #[serde(rename = {})]", rust_str(&v.name));
            }
            if let Some(m) = &v.map {
                let _ = writeln!(out, "    #[map({})]", rust_str(m));
            }
            let _ = writeln!(out, "    {ident},");
        }
        let _ = writeln!(out, "}}\n");
    }

    // ----- composite types (MongoDB `type`) -----
    for t in &schema.types {
        doc_lines(&mut out, &t.documentation, "", opts.docs);
        let _ =
            writeln!(out, "#[derive(Debug, Clone, PartialEq, ::corvis_orm::serde::Serialize, ::corvis_orm::serde::Deserialize{extra})]");
        let _ = writeln!(out, "#[serde(crate = \"::corvis_orm::serde\")]");
        let _ = writeln!(out, "pub struct {} {{", rust_ident(&t.name));
        for f in &t.fields {
            let rname = rust_ident(&snake_case(&f.name));
            doc_lines(&mut out, &f.documentation, "    ", opts.docs);
            let api = &f.db_name();
            if rname.trim_start_matches("r#") != api {
                let _ = writeln!(out, "    #[serde(rename = {})]", rust_str(api));
            }
            if f.arity == Arity::Optional {
                let _ = writeln!(out, "    #[serde(default, skip_serializing_if = \"::std::option::Option::is_none\")]");
            }
            let _ = writeln!(out, "    pub {rname}: {},", scalar_type(schema, f));
        }
        let _ = writeln!(out, "}}\n");
    }

    // ----- models -----
    for m in &schema.models {
        if ignored_model(m) {
            continue;
        }
        model(&mut out, schema, m, opts, &extra)?;
    }
    Ok(out)
}

fn base_type(schema: &Schema, ty: &str) -> String {
    match ty {
        "String" => "::std::string::String".into(),
        "Int" => "i32".into(),
        "BigInt" => "i64".into(),
        "Float" => "f64".into(),
        "Decimal" => "::corvis_orm::Decimal".into(),
        "Boolean" => "bool".into(),
        "DateTime" => "::corvis_orm::DateTime".into(),
        "Json" => "::corvis_orm::serde_json::Value".into(),
        "Bytes" => "::std::vec::Vec<u8>".into(),
        other if schema.enum_(other).is_some() || schema.composite(other).is_some() => rust_ident(other),
        other => rust_ident(other),
    }
}

fn scalar_type(schema: &Schema, f: &Field) -> String {
    let b = base_type(schema, &f.ty);
    match f.arity {
        Arity::Required => b,
        Arity::Optional => format!("::std::option::Option<{b}>"),
        Arity::List => format!("::std::vec::Vec<{b}>"),
    }
}

fn is_relation(schema: &Schema, f: &Field) -> bool {
    schema.model(&f.ty).is_some()
}

/// `@relation("name")` / `@relation(name: "name")`.
fn relation_name(f: &Field) -> Option<String> {
    f.attribute("relation").and_then(|a| a.arg_str(0, "name"))
}

fn native_type(a: &Attribute) -> String {
    let name = a.name.trim_start_matches("db.");
    if a.args.is_empty() {
        name.to_string()
    } else {
        let args: Vec<String> = a
            .args
            .iter()
            .map(|x| match &x.value {
                Expr::String(s) => s.clone(),
                other => other.to_string(),
            })
            .collect();
        format!("{name}({})", args.join(","))
    }
}

/// `#[default(...)]` for a `@default(...)`.
fn default_attr(schema: &Schema, f: &Field, e: &Expr) -> Result<String, CodegenError> {
    let is_enum = schema.enum_(&f.ty).is_some();
    Ok(match e {
        Expr::Call(name, args) => {
            let first_num = args.first().and_then(|a| match &a.value {
                Expr::Number(n) => Some(n.clone()),
                _ => None,
            });
            match name.as_str() {
                "autoincrement" | "sequence" => "autoincrement".into(),
                "now" => "now".into(),
                "uuid" => match first_num.as_deref() {
                    Some("7") => "uuid(7)".into(),
                    _ => "uuid".into(),
                },
                "cuid" => match first_num.as_deref() {
                    Some("2") => "cuid(2)".into(),
                    _ => "cuid".into(),
                },
                "nanoid" => format!("nanoid({})", first_num.unwrap_or_else(|| "21".into())),
                "ulid" => "ulid".into(),
                "dbgenerated" => {
                    let s = args.first().and_then(|a| a.value.as_str().map(str::to_string)).unwrap_or_default();
                    format!("dbgenerated({})", rust_str(&s))
                }
                "auto" => "dbgenerated(\"\")".into(),
                other => return Err(CodegenError(format!("unsupported default function `{other}()` on `{}`", f.name))),
            }
        }
        Expr::String(s) => rust_str(s),
        Expr::Number(n) => {
            if f.ty == "String" || f.ty == "Json" {
                rust_str(n)
            } else {
                n.clone()
            }
        }
        Expr::Bool(b) => b.to_string(),
        Expr::Ident(id) if is_enum => id.clone(),
        Expr::Ident(id) => return Err(CodegenError(format!("unsupported default `{id}` on `{}`", f.name))),
        Expr::Array(items) => {
            let parts: Result<Vec<String>, CodegenError> = items.iter().map(|x| default_attr(schema, f, x)).collect();
            format!("[{}]", parts?.join(", "))
        }
    })
}

fn model(out: &mut String, schema: &Schema, m: &Model, opts: &Options, extra: &str) -> Result<(), CodegenError> {
    let fields: Vec<&Field> = m.fields.iter().filter(|f| !f.has("ignore")).collect();
    let scalars: Vec<&Field> =
        fields.iter().copied().filter(|f| f.unsupported.is_none() && f.ty != "Unsupported" && !is_relation(schema, f)).collect();
    let relations: Vec<&Field> =
        fields.iter().copied().filter(|f| is_relation(schema, f) && schema.model(&f.ty).is_some_and(|t| !ignored_model(t))).collect();
    let unsupported: Vec<&Field> = fields.iter().copied().filter(|f| f.unsupported.is_some()).collect();

    // #[model(...)]
    let mut margs = vec![format!("table = {}", rust_str(&m.db_name()))];
    if let Some(s) = m.attribute("schema").and_then(|a| a.arg_str(0, "name")) {
        margs.push(format!("schema = {}", rust_str(&s)));
    }
    if m.is_view {
        margs.push("view".into());
    }
    if let Some(id) = m.attribute("id") {
        let fs = id.arg_fields(0, "fields");
        let mut s = format!("id(fields = [{}]", fs.iter().map(|x| rust_str(x)).collect::<Vec<_>>().join(", "));
        if let Some(n) = id.arg_str(99, "name") {
            let _ = write!(s, ", name = {}", rust_str(&n));
        }
        if let Some(n) = id.arg_str(99, "map") {
            let _ = write!(s, ", map = {}", rust_str(&n));
        }
        s.push(')');
        margs.push(s);
    }
    for u in m.attributes_named("unique") {
        let fs = u.arg_fields(0, "fields");
        let mut s = format!("unique(fields = [{}]", fs.iter().map(|x| rust_str(x)).collect::<Vec<_>>().join(", "));
        if let Some(n) = u.arg_str(99, "name") {
            let _ = write!(s, ", name = {}", rust_str(&n));
        }
        if let Some(n) = u.arg_str(99, "map") {
            let _ = write!(s, ", map = {}", rust_str(&n));
        }
        s.push(')');
        margs.push(s);
    }
    for i in m.attributes_named("index").chain(m.attributes_named("fulltext")) {
        let fs = i.arg_fields(0, "fields");
        let mut s = format!("index(fields = [{}]", fs.iter().map(|x| rust_str(x)).collect::<Vec<_>>().join(", "));
        if let Some(n) = i.arg_str(99, "map") {
            let _ = write!(s, ", map = {}", rust_str(&n));
        }
        let kind = if i.name == "fulltext" {
            Some("Fulltext".to_string())
        } else {
            i.named("type").and_then(|e| e.as_ident().map(str::to_string))
        };
        if let Some(k) = kind {
            let _ = write!(s, ", kind = {}", rust_str(&k));
        }
        s.push(')');
        margs.push(s);
    }
    for f in &unsupported {
        let mut s = format!(
            "unsupported(name = {}, column = {}, db = {}",
            rust_str(&f.name),
            rust_str(&f.db_name()),
            rust_str(f.unsupported.as_deref().unwrap_or_default())
        );
        if f.arity == Arity::Optional {
            s.push_str(", optional");
        }
        s.push(')');
        margs.push(s);
    }

    doc_lines(out, &m.documentation, "", opts.docs);
    let _ = writeln!(
        out,
        "#[derive(Debug, Clone, PartialEq, ::corvis_orm::serde::Serialize, ::corvis_orm::serde::Deserialize, ::corvis_orm::Model{extra})]"
    );
    let _ = writeln!(out, "#[serde(crate = \"::corvis_orm::serde\")]");
    if margs.len() <= 2 {
        let _ = writeln!(out, "#[model({})]", margs.join(", "));
    } else {
        let _ = writeln!(out, "#[model(\n    {},\n)]", margs.join(",\n    "));
    }
    let _ = writeln!(out, "pub struct {} {{", rust_ident(&m.name));

    for f in &scalars {
        doc_lines(out, &f.documentation, "    ", opts.docs);
        let rname = rust_ident(&snake_case(&f.name));
        let bare = rname.trim_start_matches("r#");
        if bare != f.name {
            let _ = writeln!(out, "    #[serde(rename = {})]", rust_str(&f.name));
        }
        let col = f.db_name();
        if col != bare {
            let _ = writeln!(out, "    #[map({})]", rust_str(&col));
        }
        if let Some(id) = f.attribute("id") {
            match id.arg_str(99, "map") {
                Some(map) => {
                    let _ = writeln!(out, "    #[id(map = {})]", rust_str(&map));
                }
                None => {
                    let _ = writeln!(out, "    #[id]");
                }
            }
        }
        if f.has("unique") {
            let _ = writeln!(out, "    #[unique]");
        }
        if let Some(d) = f.attribute("default")
            && let Some(e) = d.arg(0, "value")
        {
            let _ = writeln!(out, "    #[default({})]", default_attr(schema, f, e)?);
        }
        if f.has("updatedAt") {
            let _ = writeln!(out, "    #[updated_at]");
        }
        if let Some(n) = f.native_type() {
            let _ = writeln!(out, "    #[db({})]", rust_str(&native_type(n)));
        }
        if !SCALARS.contains(&f.ty.as_str()) && schema.composite(&f.ty).is_some() {
            let _ = writeln!(out, "    #[db_type(Json)]");
        }
        let _ = writeln!(out, "    pub {rname}: {},", scalar_type(schema, f));
    }

    let mut has_to_many = false;
    for f in &relations {
        doc_lines(out, &f.documentation, "    ", opts.docs);
        let rname = rust_ident(&snake_case(&f.name));
        let bare = rname.trim_start_matches("r#");
        let target = schema.model(&f.ty).unwrap();
        let rel_name = relation_name(f);
        let attr = f.attribute("relation");
        let fk = attr.map(|a| a.arg_fields(99, "fields")).unwrap_or_default();
        let mut args: Vec<String> = Vec::new();
        if !fk.is_empty() {
            args.push("belongs_to".into());
            let refs = attr.map(|a| a.arg_fields(99, "references")).unwrap_or_default();
            args.push(format!("fields = [{}]", fk.iter().map(|x| rust_str(x)).collect::<Vec<_>>().join(", ")));
            args.push(format!("references = [{}]", refs.iter().map(|x| rust_str(x)).collect::<Vec<_>>().join(", ")));
            if let Some(a) = attr.and_then(|a| a.named("onDelete")).and_then(|e| e.as_ident()) {
                args.push(format!("on_delete = {}", rust_str(a)));
            }
            if let Some(a) = attr.and_then(|a| a.named("onUpdate")).and_then(|e| e.as_ident()) {
                args.push(format!("on_update = {}", rust_str(a)));
            }
            if let Some(map) = attr.and_then(|a| a.named("map")).and_then(|e| e.as_str()) {
                args.push(format!("map = {}", rust_str(map)));
            }
        } else if f.arity == Arity::List {
            // The other side: a list too (implicit many-to-many) or a to-one with `fields`.
            let opposite = target
                .fields
                .iter()
                .find(|o| o.ty == m.name && relation_name(o) == rel_name && !(m.name == target.name && o.name == f.name));
            let m2m = opposite.is_some_and(|o| o.arity == Arity::List);
            args.push(if m2m { "many_to_many".into() } else { "has_many".into() });
        } else {
            args.push("has_one".into());
        }
        if let Some(n) = &rel_name {
            args.push(format!("name = {}", rust_str(n)));
        }
        if bare != f.name {
            let _ = writeln!(out, "    #[serde(rename = {})]", rust_str(&f.name));
        }
        let _ = writeln!(out, "    #[relation({})]", args.join(", "));
        let t = rust_ident(&target.name);
        match f.arity {
            Arity::List => {
                has_to_many = true;
                let _ = writeln!(out, "    #[serde(default, skip_serializing_if = \"::std::option::Option::is_none\")]");
                let _ = writeln!(out, "    pub {rname}: ::std::option::Option<::std::vec::Vec<{t}>>,");
            }
            Arity::Required => {
                let _ = writeln!(out, "    #[serde(default, skip_serializing_if = \"::std::option::Option::is_none\")]");
                let _ = writeln!(out, "    pub {rname}: ::std::option::Option<::std::boxed::Box<{t}>>,");
            }
            Arity::Optional => {
                let _ = writeln!(
                    out,
                    "    #[serde(default, skip_serializing_if = \"::std::option::Option::is_none\", with = \"::corvis_orm::serde_helpers::double_option\")]"
                );
                let _ = writeln!(out, "    pub {rname}: ::std::option::Option<::std::option::Option<::std::boxed::Box<{t}>>>,");
            }
        }
    }
    if has_to_many {
        let _ = writeln!(out, "    /// `_count` of the to-many relations, present when selected.");
        let _ = writeln!(out, "    #[skip]");
        let _ = writeln!(out, "    #[serde(rename = \"_count\", default, skip_serializing_if = \"::std::option::Option::is_none\")]");
        let _ = writeln!(out, "    pub _count: ::std::option::Option<::corvis_orm::serde_json::Value>,");
    }
    let _ = writeln!(out, "}}\n");
    Ok(())
}

/// Parses `src` and generates the Rust module.
pub fn generate_from_str(src: &str, opts: &Options) -> Result<String, Box<dyn std::error::Error + Send + Sync>> {
    let schema = crate::psl::parse(src)?;
    Ok(generate(&schema, opts)?)
}
