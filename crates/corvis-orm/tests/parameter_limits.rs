//! Statements the engine builds from a list of keys stay within the database's parameter limit (32766 on SQLite,
//! 65535 on Postgres), whatever the number of keys: read-backs of `createManyAndReturn` / `updateManyAndReturn`,
//! includes and counts over a compound key, nested `set` / `disconnect` / `deleteMany` lists and `in` with
//! `mode: insensitive`. The statement counts are checked by the unit tests of the engine (`src/engine/`).

#[path = "common/pg.rs"]
mod pg;

use corvis_orm::Dialect;
use corvis_orm::prelude::*;

#[derive(Debug, Clone, Serialize, Deserialize, Model)]
#[model(table = "items")]
pub struct Item {
    #[id]
    #[default(autoincrement)]
    pub id: i64,
    pub name: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, Model)]
#[model(table = "pairs", id(fields = ["a", "b"]))]
pub struct Pair {
    pub a: String,
    pub b: i64,
    #[relation(has_many)]
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub entries: Option<Vec<Entry>>,
}

#[derive(Debug, Clone, Serialize, Deserialize, Model)]
#[model(table = "entries")]
pub struct Entry {
    #[id]
    #[default(autoincrement)]
    pub id: i64,
    pub pair_a: String,
    pub pair_b: i64,
    #[relation(belongs_to, fields = ["pair_a", "pair_b"], references = ["a", "b"])]
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub pair: Option<Box<Pair>>,
}

#[derive(Debug, Clone, Serialize, Deserialize, Model)]
#[model(table = "parents")]
pub struct Parent {
    #[id]
    #[default(autoincrement)]
    pub id: i64,
    #[relation(has_many)]
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub children: Option<Vec<Child>>,
    #[relation(many_to_many)]
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tags: Option<Vec<Tag>>,
}

#[derive(Debug, Clone, Serialize, Deserialize, Model)]
#[model(table = "children")]
pub struct Child {
    #[id]
    #[default(autoincrement)]
    pub id: i64,
    pub parent_id: Option<i64>,
    #[relation(belongs_to, fields = "parent_id")]
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub parent: Option<Box<Parent>>,
}

#[derive(Debug, Clone, Serialize, Deserialize, Model)]
#[model(table = "Tag")]
pub struct Tag {
    #[id]
    #[default(autoincrement)]
    pub id: i64,
    #[relation(many_to_many)]
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub parents: Option<Vec<Parent>>,
}

type Models = (Item, Pair, Entry, Parent, Child, Tag);

fn meta<M: corvis_orm::Model>() -> &'static corvis_orm::ModelMeta {
    M::meta()
}

async fn q(db: &OrmClient, model: &'static corvis_orm::ModelMeta, action: &str, args: Value) -> Value {
    match db.query_json(model, action, args).await {
        Ok(v) => v,
        Err(e) => panic!("{}.{action}: {e}", model.name),
    }
}

async fn sqlite() -> OrmClient {
    let db = OrmClient::new("sqlite::memory:").unwrap();
    db.db_push::<Models>().await.unwrap();
    db
}

async fn postgres(name: &str) -> Option<OrmClient> {
    let db = OrmClient::new(pg::fresh_db(&format!("limits_{name}")).await?).unwrap();
    db.db_push::<Models>().await.unwrap();
    Some(db)
}

/// `INSERT INTO <table> (<cols>) SELECT <exprs of x> FROM 1..=n`, generated by the database.
async fn seed(db: &OrmClient, table: &str, cols: &str, exprs: &str, n: usize) {
    let sql = match db.dialect() {
        Dialect::Sqlite => format!(
            "WITH RECURSIVE s(x) AS (SELECT 1 UNION ALL SELECT x + 1 FROM s WHERE x < {n}) INSERT INTO \"{table}\" ({cols}) SELECT {exprs} FROM s"
        ),
        Dialect::Postgres => format!("INSERT INTO \"{table}\" ({cols}) SELECT {exprs} FROM generate_series(1, {n}) AS s(x)"),
    };
    db.db_execute(&sql).await.unwrap();
}

fn concat(db: &OrmClient, prefix: &str) -> String {
    match db.dialect() {
        Dialect::Sqlite => format!("'{prefix}' || x"),
        Dialect::Postgres => format!("'{prefix}' || x::text"),
    }
}

async fn create_many_and_return(db: &OrmClient, n: usize) {
    let data: Vec<Value> = (0..n).map(|i| json!({ "name": format!("n{i}") })).collect();
    let rows = q(db, meta::<Item>(), "createManyAndReturn", json!({ "data": data })).await;
    let names: Vec<&str> = rows.as_array().unwrap().iter().map(|r| r["name"].as_str().unwrap()).collect();
    assert_eq!(names.len(), n);
    assert!(names.iter().enumerate().all(|(i, name)| *name == format!("n{i}")), "rows are not in input order");
}

async fn update_many_and_return(db: &OrmClient, n: usize) {
    seed(db, "items", "\"name\"", &concat(db, "n"), n).await;
    let rows =
        q(db, meta::<Item>(), "updateManyAndReturn", json!({ "where": { "name": { "startsWith": "n" } }, "data": { "name": "u" } })).await;
    let rows = rows.as_array().unwrap();
    assert_eq!(rows.len(), n);
    assert!(rows.iter().all(|r| r["name"] == "u"));
}

async fn include_over_a_compound_key(db: &OrmClient, n: usize) {
    seed(db, "pairs", "\"a\", \"b\"", &format!("{}, x", concat(db, "p")), n).await;
    seed(db, "entries", "\"pair_a\", \"pair_b\"", &format!("{}, x", concat(db, "p")), n).await;
    let pairs =
        q(db, meta::<Pair>(), "findMany", json!({ "include": { "entries": true, "_count": { "select": { "entries": true } } } })).await;
    let pairs = pairs.as_array().unwrap();
    assert_eq!(pairs.len(), n);
    for p in pairs {
        let entries = p["entries"].as_array().unwrap();
        assert_eq!(entries.len(), 1, "{p}");
        assert_eq!((&entries[0]["pair_a"], &entries[0]["pair_b"]), (&p["a"], &p["b"]), "{p}");
        assert_eq!(p["_count"]["entries"], 1, "{p}");
    }
}

async fn nested_set_and_delete_many(db: &OrmClient, n: usize) {
    q(db, meta::<Parent>(), "create", json!({ "data": {} })).await;
    seed(db, "children", "\"parent_id\"", "NULL", n).await;
    let all: Vec<Value> = (1..=n).map(|i| json!({ "id": i })).collect();
    let children_of_1 = |db: &OrmClient| {
        let db = db.clone();
        async move { q(&db, meta::<Child>(), "count", json!({ "where": { "parent_id": 1 } })).await }
    };
    q(db, meta::<Parent>(), "update", json!({ "where": { "id": 1 }, "data": { "children": { "set": all } } })).await;
    assert_eq!(children_of_1(db).await, json!(n), "set connects every child");
    // Dropping all but ten clears the foreign key of the others.
    let ten: Vec<Value> = (1..=10).map(|i| json!({ "id": i })).collect();
    q(db, meta::<Parent>(), "update", json!({ "where": { "id": 1 }, "data": { "children": { "set": ten } } })).await;
    assert_eq!(children_of_1(db).await, json!(10), "set disconnects the others");
    q(db, meta::<Parent>(), "update", json!({ "where": { "id": 1 }, "data": { "children": { "set": all } } })).await;
    let some: Vec<Value> = (1..=n).filter(|i| i % 2 == 0).map(|i| json!({ "id": i })).collect();
    q(db, meta::<Parent>(), "update", json!({ "where": { "id": 1 }, "data": { "children": { "deleteMany": some } } })).await;
    assert_eq!(q(db, meta::<Child>(), "count", json!({})).await, json!(n - n / 2), "deleteMany deletes every listed child");
}

async fn m2m_disconnect(db: &OrmClient, n: usize) {
    q(db, meta::<Parent>(), "create", json!({ "data": {} })).await;
    seed(db, "Tag", "\"id\"", "x", n).await;
    seed(db, "_ParentToTag", "\"A\", \"B\"", "1, x", n).await;
    let all: Vec<Value> = (1..=n).map(|i| json!({ "id": i })).collect();
    let parent = q(
        db,
        meta::<Parent>(),
        "update",
        json!({ "where": { "id": 1 }, "data": { "tags": { "disconnect": all } }, "include": { "_count": true } }),
    )
    .await;
    assert_eq!(parent["_count"]["tags"], 0, "{parent}");
}

async fn insensitive_in(db: &OrmClient, n: usize) {
    seed(db, "items", "\"name\"", &concat(db, "Name"), n).await;
    let names: Vec<String> = (1..=n).map(|i| format!("nAME{i}")).collect();
    let count = q(db, meta::<Item>(), "count", json!({ "where": { "name": { "in": names, "mode": "insensitive" } } })).await;
    assert_eq!(count, json!(n));
    let none = q(db, meta::<Item>(), "count", json!({ "where": { "name": { "notIn": names, "mode": "insensitive" } } })).await;
    assert_eq!(none, json!(0));
}

